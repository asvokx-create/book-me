import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { loadHourlyBackend } from "./helpers/hourly-test-backend.ts";
type Backend = typeof import("../lib/hourly-projects");
// Execute real server SQL in PostgreSQL WASM; only external boundaries/time are stubbed.
const loadBackend = (database: unknown) => loadHourlyBackend<Backend>(database);
test("real hourly project SQL: history preservation, permissions, cap, corrections, approval locks", async () => {
  const db = new PGlite();
  let now = new Date("2026-11-09T12:00:00Z");
  try {
    await db.exec(`
      CREATE TABLE "user" (id text PRIMARY KEY, name text NOT NULL);
      CREATE TABLE provider_profiles (id uuid PRIMARY KEY, user_id text NOT NULL REFERENCES "user"(id), business_name text NOT NULL, is_active boolean NOT NULL DEFAULT true, age_verification_status text NOT NULL DEFAULT 'verified');
      CREATE TABLE services (id uuid PRIMARY KEY, provider_id uuid NOT NULL REFERENCES provider_profiles(id), title text NOT NULL, hourly_rate_cents integer NOT NULL, pricing_type text NOT NULL DEFAULT 'HOURLY', delivery_type text NOT NULL DEFAULT 'REMOTE', is_active boolean NOT NULL DEFAULT true, provider_deleted_at timestamptz);
      CREATE TABLE bookings (id uuid PRIMARY KEY, payment_status text NOT NULL, price_cents integer NOT NULL, customer_total_cents integer NOT NULL);
      CREATE TABLE booking_events (booking_id uuid REFERENCES bookings(id), event_type text, metadata jsonb, created_at timestamptz DEFAULT now());
      CREATE TABLE notifications(user_id text,type text,title text,message text,href text,dedupe_key text UNIQUE);
      CREATE TABLE account_restrictions (id uuid DEFAULT gen_random_uuid(), user_id text NOT NULL, status text NOT NULL, expires_at timestamptz);
      INSERT INTO "user" VALUES ('customer','Customer'),('provider','Provider'),('stranger','Other person');
      INSERT INTO provider_profiles(id,user_id,business_name) VALUES ('00000000-0000-4000-8000-000000000001','provider','Service Co');
      INSERT INTO services(id,provider_id,title,hourly_rate_cents) VALUES ('00000000-0000-4000-8000-000000000002','00000000-0000-4000-8000-000000000001','Repair work',6000);
      INSERT INTO bookings VALUES ('00000000-0000-4000-8000-000000000003','paid',12000,12299);
    `);
    const migration = readFileSync("database/migrations/111_hourly_projects.sql", "utf8");
    const before = (await db.query("SELECT * FROM bookings")).rows;
    await db.exec(migration);
    await db.exec(migration);
    assert.deepEqual((await db.query("SELECT * FROM bookings")).rows, before, "repeat migration cannot rewrite a historical payment");
    const query = async (sql: string, values: unknown[] = []) => {
      if (sql.includes("pg_advisory_xact_lock")) return { rows: [], rowCount: 1 };
      if (sql === "SELECT clock_timestamp() AS now") return { rows: [{ now }], rowCount: 1 };
      const result = await db.query(sql, values);
      return { ...result, rowCount: result.affectedRows || result.rows.length };
    };
    const backend = loadBackend({ query, connect: async () => ({ query, release() {} }) });
    const input = { serviceId: "00000000-0000-4000-8000-000000000002", description: "Fix the project safely", capMinutes: 2, deliveryMethod: "REMOTE", hourlyRateCents: 1 };
    let p = await backend.createHourlyProject("customer", input);
    assert.equal(p.hourlyRateCents, 6000, "rate must come from listing, never browser");
    assert.equal(p.status, "requested");
    assert.equal((await backend.createHourlyProject("customer", input)).id, p.id, "double submission reuses open project");
    assert.equal((await db.query<{ count: number }>("SELECT count(*)::int AS count FROM notifications")).rows[0].count,1,"creation retry must not duplicate notification");
    assert.equal((await backend.getHourlyProject("provider",p.id)).serviceAddress,"Address available after acceptance");
    assert.equal((await backend.getHourlyProject("customer",p.id)).serviceAddress,"Remote service");
    await assert.rejects(backend.createHourlyProject("provider", input), /own service/);
    await assert.rejects(backend.getHourlyProject("stranger", p.id), /not found/);
    assert.deepEqual(await backend.listHourlyProjects("stranger"), []);
    await assert.rejects(backend.mutateHourlyProject("customer", p.id, { action: "accept", version: p.version }), /Only the provider/);
    p = await backend.mutateHourlyProject("provider", p.id, { action: "accept", version: p.version });
    assert.equal(p.serviceAddress,"Remote service","provider gets address after acceptance");
    assert.ok((await db.query("SELECT 1 FROM notifications WHERE user_id='customer' AND title='Hourly project accepted'")).rows.length);
    const stale = p.version;
    p = await backend.mutateHourlyProject("provider", p.id, { action: "start", version: p.version, description: "Repair" });
    await assert.rejects(backend.mutateHourlyProject("provider", p.id, { action: "start", version: stale }), /changed/);
    now = new Date(now.getTime() + 30_000);
    p = await backend.getHourlyProject("customer", p.id);
    assert.equal(p.totalSeconds, 30);
    assert.equal(p.billableMinutes, 1);
    assert.equal(p.subtotalCents, 100);
    p = await backend.mutateHourlyProject("customer", p.id, { action: "increase_cap", version: p.version, capMinutes: 3 });
    now = new Date(now.getTime() + 600_000);
    p = await backend.getHourlyProject("customer", p.id);
    assert.equal(p.totalSeconds, 120, "cap increase cannot retroactively extend an unattended timer");
    p = await backend.mutateHourlyProject("provider", p.id, { action: "stop", version: p.version });
    assert.equal(p.totalSeconds, 120);
    await assert.rejects(backend.mutateHourlyProject("provider", p.id, { action: "add_entry", version: p.version, durationMinutes: 2 }), /exceed/);
    p = await backend.mutateHourlyProject("provider", p.id, { action: "add_entry", version: p.version, durationMinutes: 1, description: "Cleanup" });
    assert.equal(p.totalSeconds, 180);
    await assert.rejects(backend.mutateHourlyProject("provider", p.id, { action: "start", version: p.version }), /cap/);
    await assert.rejects(backend.mutateHourlyProject("customer", p.id, { action: "cancel", version: p.version }), /cannot be cancelled/);
    p = await backend.mutateHourlyProject("provider", p.id, { action: "submit", version: p.version });
    assert.equal(p.status, "submitted");
    assert.equal(p.customerTotalCents, 599);
    await assert.rejects(backend.mutateHourlyProject("provider", p.id, { action: "edit_entry", version: p.version, entryId: p.entries[0].id, durationMinutes: 1 }), /active/);
    p = await backend.mutateHourlyProject("customer", p.id, { action: "request_changes", version: p.version, description: "Please correct cleanup" });
    p = await backend.mutateHourlyProject("provider", p.id, { action: "delete_entry", version: p.version, entryId: p.entries.find((e: { source: string }) => e.source === "manual")!.id });
    assert.equal(p.totalSeconds, 120);
    assert.ok(p.history.some((event: { action: string }) => event.action === "delete_entry"), "correction must remain in history");
    p = await backend.mutateHourlyProject("provider", p.id, { action: "submit", version: p.version });
    const snapshot = (await db.query("SELECT submitted_seconds,submitted_minutes,submitted_subtotal_cents FROM hourly_projects WHERE id=$1", [p.id])).rows[0];
    assert.deepEqual(snapshot, { submitted_seconds: 120, submitted_minutes: 2, submitted_subtotal_cents: 200 });
    await db.query("UPDATE hourly_projects SET status='approved',approved_at=now(),payment_booking_id='00000000-0000-4000-8000-000000000003' WHERE id=$1", [p.id]);
    await assert.rejects(backend.mutateHourlyProject("provider", p.id, { action: "delete_entry", version: p.version, entryId: p.entries[0].id }), /locked/);
    p = await backend.getHourlyProject("customer", p.id);
    assert.equal(p.paymentStatus, "paid");
    assert.deepEqual((await db.query("SELECT * FROM bookings")).rows, before);
    await db.query("INSERT INTO booking_events(booking_id,event_type,metadata) VALUES($1,'timesheet_approved',$2)", [p.paymentBookingId, JSON.stringify({version:p.version,minutes:2,subtotalCents:200})]);
    p = await backend.getHourlyProject("customer", p.id);
    assert.ok(p.history.some((event: { action:string; createdAt:unknown }) => event.action === "approve" && event.createdAt));
    let fresh = await backend.createHourlyProject("customer", input);
    fresh = await backend.mutateHourlyProject("provider", fresh.id, {action:"accept",version:fresh.version});
    fresh = await backend.mutateHourlyProject("provider", fresh.id, {action:"add_entry",version:fresh.version,durationMinutes:1});
    fresh = await backend.mutateHourlyProject("provider", fresh.id, {action:"delete_entry",version:fresh.version,entryId:fresh.entries[0].id});
    fresh = await backend.mutateHourlyProject("customer", fresh.id, {action:"cancel",version:fresh.version});
    assert.equal(fresh.status,"cancelled","zero corrected time can close without losing audit history");
    assert.ok(fresh.history.some((event:{action:string})=>event.action==="delete_entry"));
    fresh = await backend.createHourlyProject("customer", input);
    await db.query("INSERT INTO account_restrictions(user_id,status) VALUES ('customer','suspended')");
    await assert.rejects(backend.createHourlyProject("customer",input),/restricted/);
    await assert.rejects(backend.mutateHourlyProject("customer",fresh.id,{action:"cancel",version:fresh.version}),/restricted/);
    await db.query("DELETE FROM account_restrictions");
    await db.query("INSERT INTO account_restrictions(user_id,status) VALUES ('provider','banned')");
    await assert.rejects(backend.createHourlyProject("customer",input),/restricted/);
    await assert.rejects(backend.mutateHourlyProject("provider",fresh.id,{action:"accept",version:fresh.version}),/restricted/);
    await db.query("DELETE FROM account_restrictions");
    fresh = await backend.mutateHourlyProject("provider",fresh.id,{action:"accept",version:fresh.version});
    await db.query("UPDATE provider_profiles SET is_active=false");
    await assert.rejects(backend.mutateHourlyProject("provider",fresh.id,{action:"start",version:fresh.version}),/active, verified/);
    await db.query("UPDATE provider_profiles SET is_active=true");
    fresh = await backend.mutateHourlyProject("provider",fresh.id,{action:"start",version:fresh.version});
    const providerId="00000000-0000-4000-8000-000000000001";
    // A second project for the same provider cannot bypass the DB running index.
    const another=(await db.query<{id:string}>("INSERT INTO hourly_projects(customer_id,provider_id,service_id,title,description,hourly_rate_cents,cap_minutes,delivery_method,service_address) VALUES('stranger',$1,$2,'Another','Another project',6000,2,'REMOTE','Remote') RETURNING id",[providerId,input.serviceId])).rows[0];
    await assert.rejects(db.query("INSERT INTO hourly_time_entries(project_id,provider_id,source,timer_limit_seconds) VALUES($1,$2,'timer',60)",[another.id,providerId]),/hourly_one_running_timer_per_provider/);
    await db.query("INSERT INTO provider_profiles(id,user_id,business_name) VALUES('00000000-0000-4000-8000-000000000004','stranger','Other Provider')");
    await assert.rejects(db.query("INSERT INTO hourly_time_entries(project_id,provider_id,source,timer_limit_seconds) VALUES($1,'00000000-0000-4000-8000-000000000004','timer',60)",[fresh.id]),/foreign key/);
    now=new Date(now.getTime()+1500);
    fresh=await backend.mutateHourlyProject("provider",fresh.id,{action:"stop",version:fresh.version});
    assert.equal(fresh.totalSeconds,1,"stop persists only full elapsed seconds");
    fresh=await backend.mutateHourlyProject("provider",fresh.id,{action:"edit_entry",version:fresh.version,entryId:fresh.entries[0].id,durationMinutes:1,description:"Corrected work"});
    assert.equal(fresh.totalSeconds,60);
  } finally { await db.close(); }
});
